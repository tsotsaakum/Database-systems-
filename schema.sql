-- PostgreSQL schema for the ITDSA order database.
-- Transcribed from Sivuziwe Tsotsa's ITDSA submission, 25 August 2025.
-- The submission described AUTO_INCREMENT primary keys.
-- This script uses IDENTITY, the PostgreSQL equivalent.
-- Supplier contact email was listed as VARCHAR(20) in the submission.
-- This script uses VARCHAR(100) so a normal email address fits.

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20),
    address VARCHAR(255) NOT NULL,
    CONSTRAINT customers_email_format CHECK (email LIKE '%@%.%'),
    CONSTRAINT customers_phone_format CHECK (phone_number LIKE '0%')
);

CREATE TABLE suppliers (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    contact_email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20),
    CONSTRAINT suppliers_phone_format CHECK (phone_number LIKE '0%')
);

CREATE TABLE products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    supplier_id INTEGER NOT NULL REFERENCES suppliers (supplier_id)
);

CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date TIMESTAMP NOT NULL,
    customer_id INTEGER NOT NULL REFERENCES customers (customer_id),
    total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders (order_id),
    product_id INTEGER NOT NULL REFERENCES products (product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0),
    UNIQUE (order_id, product_id)
);

-- Denormalised summary from the business-intelligence section.
CREATE TABLE customer_summary (
    customer_id INTEGER PRIMARY KEY REFERENCES customers (customer_id),
    customer_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    total_orders INTEGER NOT NULL,
    total_amount_spent NUMERIC(12, 2) NOT NULL
);
